/**
 * Builds src/game/cat-sprite.ts: the signature cat glyph as a small data URI so the game
 * engine (and the self-contained offline page) needs no image request to draw the player.
 * Run: ./node_modules/.bin/tsx scripts/game-sprite.ts
 */
import { readFileSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const SRC = "public/brand/signature.png";
const OUT = "src/game/cat-sprite.ts";
const HEIGHT = 192;

const trimmed = sharp(SRC).ensureAlpha().trim();
const { data, info } = await trimmed
  .resize({ height: HEIGHT, kernel: "lanczos3" })
  .raw()
  .toBuffer({ resolveWithObject: true });

// Keep only the alpha channel: the engine tints the glyph itself, so colour is noise here.
const alpha = Buffer.alloc(info.width * info.height);
for (let i = 0; i < alpha.length; i++) {
  // The source is white on transparent; use alpha as the mask, ignore RGB.
  alpha[i] = data[i * info.channels + 3]!;
}
const png = await sharp(alpha, {
  raw: { width: info.width, height: info.height, channels: 1 },
})
  .png({ palette: true, colors: 16, compressionLevel: 9, effort: 10 })
  .toBuffer();

const uri = `data:image/png;base64,${png.toString("base64")}`;
const file = `// Generated by scripts/game-sprite.ts from public/brand/signature.png. Do not edit.
// A greyscale mask of the signature cat glyph: white where the glyph is, ${info.width}x${info.height}.
export const CAT_SPRITE = {
  width: ${info.width},
  height: ${info.height},
  src:
    "${uri}",
} as const;
`;
writeFileSync(OUT, file);
console.log(`${OUT}: ${info.width}x${info.height}, ${(png.length / 1024).toFixed(1)} KB png`);

// The Findabis mark, printed on every spray can as the studio's small credit. Rendered in
// ink at a fixed size (it is only ever drawn on jade), so no tinting is needed at runtime.
const MARK_SRC = "public/brand/findabis-icon.svg";
const MARK_OUT = "src/game/findabis-sprite.ts";
const MARK_SIZE = 40;
const svg = readFileSync(MARK_SRC, "utf8").replace(/fill:\s*#01c7a4/g, "fill:#07060b");
const mark = await sharp(Buffer.from(svg), { density: 300 })
  .resize({ width: MARK_SIZE, height: MARK_SIZE, fit: "contain", background: { r: 0, g: 0, b: 0, alpha: 0 } })
  .png({ palette: true, colors: 8, compressionLevel: 9, effort: 10 })
  .toBuffer();
const markMeta = await sharp(mark).metadata();
writeFileSync(
  MARK_OUT,
  `// Generated by scripts/game-sprite.ts from public/brand/findabis-icon.svg. Do not edit.
// The Findabis mark in ink on transparent, ${markMeta.width}x${markMeta.height}, printed on the cans.
export const FINDABIS_MARK = {
  width: ${markMeta.width},
  height: ${markMeta.height},
  src:
    "data:image/png;base64,${mark.toString("base64")}",
} as const;
`,
);
console.log(`wrote ${MARK_OUT} (${mark.length} bytes)`);
